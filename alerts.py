"""Алерты «касание уровня»: правило срабатывания.

Отдельный модуль, потому что правило чистое (числа на входе, bool на выходе) и его
надо тестировать без сети и без базы. Всё остальное вокруг алертов лежит там же, где
и у сигналов: хранение — database.py, фоновая проверка — scheduler.check_alerts,
кнопки и сценарий — bot.py.

Главная мысль правила: касание ловится ДИАПАЗОНОМ свечей за период между проверками,
а не одной точкой. Проверка идёт раз в config.ALERT_EVERY_MIN минут; если за это время
цена сходила к уровню фитилём и вернулась, одна точка это пропустит, а диапазон
минутных свечей — нет. Опоздание до одного интервала проверки при этом нормально.

История: алерты убирались из бота 20 августа 2026 вместе со всем, что не движок, и
вернулись 26 августа. Разница с прежней версией одна, но существенная — цену теперь
берём оттуда же, откуда движок берёт уровни (фьючерсы BingX), а не с Yahoo. Раньше
уровень считался по одному инструменту, а касание проверялось по другому: у золота,
TON и валютных пар биржевая синтетика и котировка Yahoo — это разные графики. В тот
же день Yahoo убрали из бота целиком, и развилки по источнику не осталось нигде.
"""


def window_from_candles(df) -> dict:
    """Свечи (DataFrame OHLCV) → {low, high, last} за весь переданный кусок.

    low/high — куда цена заходила за период, last — последняя цена. Больше правилу
    срабатывания ничего не нужно, поэтому функция ничего не знает про инструмент:
    свечи и свечи.
    """
    return {
        "low": float(df["low"].min()),
        "high": float(df["high"].max()),
        "last": float(df["close"].iloc[-1]),
    }


def side_of(last: float, threshold: float) -> int:
    """С какой стороны уровня цена: 1 — на уровне или выше, 0 — ниже."""
    return 1 if last >= threshold else 0


def hit(low: float, high: float, last: float, threshold: float, start_above: int) -> bool:
    """Сработал ли алерт на уровне `threshold`.

    Два признака, любого достаточно:
      • touched — уровень побывал внутри диапазона свечей, то есть цена доходила до
        него хотя бы фитилём. Это основной признак;
      • crossed — цена оказалась по другую сторону уровня, чем была при постановке.
        Запасной признак на случай, когда диапазона нет (одна точка) или уровень
        перескочили разрывом, не коснувшись, — а такое у валютных пар бывает: у них
        выходные, и понедельник открывается гэпом.
    """
    touched = low <= threshold <= high
    crossed = side_of(last, threshold) != start_above
    return touched or crossed
