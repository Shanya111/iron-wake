# Это НЕ настройка сигналов — зоны показываются только в отчёте /analyze, на отбор
# сигналов они не влияли. Поэтому порог убран из /settings (он там путал: стоял
# в меню «настройки движка сигналов», но сигналы им не управлялись) и зафиксирован.
LIQUIDITY_MULT = 1.5

# ── Паттерны (Spring / Upthrust) ────────────────────────────────────────────
VOL_LOOKBACK = 20       # сколько свечей берём для среднего объёма
# Как решаем, что объём на свече пробоя аномальный. Два способа:
#   VOL_MODE = "pctl" — объём выше VOL_PCTL-го процентиля за последние VOL_WINDOW
#     свечей, то есть «один из самых высоких столбиков среди соседних» (по умолчанию).
#     Ближе к самой методике VSA: там нет фиксированного множителя, объём относителен.
#   VOL_MODE = "mult" — объём ≥ среднего за VOL_LOOKBACK свечей × VOL_MULT. Как было
#     раньше; оставлен рабочим, на нём бэктест гоняет варианты для сравнения.
# Z-Score сознательно не используем: объём распределён с сильным перекосом, редкие
# выбросы сами раздувают стандартное отклонение и портят меру. Процентиль устойчивее.
#
# Почему P70 за 50 свечей. Прогон 23 вариантов порога (множители ×1.0…×1.5 и
# процентили P50…P95 по окнам 20/50/100) на 6 инструментах, один срез данных:
#
#   вариант        сделок   сумма R   R/сделку   калибровка   проверка
#   ×1.5 (было)       212     +91.7     +0.433      +72.1       +19.6
#   P70 / 50          306    +138.6     +0.453      +89.8       +48.7
#   ×1.1              308    +124.6     +0.405      +76.6       +48.1
#
# Главное, что вскрыл замер: старый порог ×1.5 был УБЫТОЧЕН на крипте на проверочной
# половине истории (−11.3R), а общий плюс делали золото с нефтью (+30.9R) — в сводной
# таблице одно закрывало другое. С P70 крипта даёт +14.1R.
#
# ВАЖНО, чтобы потом не переоценить: преимущество процентиля как МЕРЫ — внутри
# погрешности. Простое ослабление множителя до ×1.1 даёт почти то же (+48.1 против
# +48.7 на проверке). Основной выигрыш — от ослабления порога вообще. За процентиль
# говорит второй довод, не статистический: «верхние 30% свежих свечей» значат одно и
# то же для золота с Yahoo (объём неполный) и для биткоина с Kraken, а «×1.1» — разное,
# потому что зависит от формы распределения объёма. Проверять — `python backtest.py
# --all --sweep vol --by-source`, см. «Бэктест» в CLAUDE.md.
VOL_MODE = "pctl"
VOL_PCTL = 70           # процентиль объёма (режим "pctl"): выше него → аномальный
VOL_WINDOW = 50         # по скольким последним свечам считаем процентиль
VOL_MULT = 1.5          # множитель среднего (режим "mult") — запасной путь и бэктест
# Запас стопа за экстремум свечи пробоя. Два способа задать:
#   STOP_MODE = "pct" — запас = STOP_SPREAD × цена (по умолчанию);
#   STOP_MODE = "atr" — запас = STOP_ATR_MULT × ATR(STOP_ATR_PERIOD) на H1 в момент
#     сигнала: стоп сам подстраивается под волатильность инструмента и момента.
#
# Почему по умолчанию процент, а не ATR. Идея «одним процентом биткоину и золоту не
# угодить» звучит убедительно, но прогон 12 вариантов стопа по 6 инструментам
# (~1200 сигналов, крипта год, золото/нефть 1.5 года) её не подтвердил — процент
# выигрывает у ATR на всех срезах, R на сделку:
#
#   вариант     сделок   сумма R   R/сделку   1-я половина   2-я половина
#   0.1%           274     +77.3     +0.282       +0.457         +0.122
#   0.3%           143     +41.4     +0.289       +0.433         +0.148
#   ATR×0.25       209     +46.3     +0.222       +0.391         +0.050
#   ATR×0.5        112     +15.3     +0.136       +0.279         −0.006
#
# Расширение буфера (до 1.2% и до ATR×3.0) только срезает число сигналов и уводит
# итог в минус: «выбило-и-поехало» падает с 39% до нуля, но вместе с потерями
# уходит и вся прибыль. Риск на сделку задаёт размах свечи пробоя (~1% цены), а не
# сам буфер, поэтому добавка к нему почти ничего не меняет.
#
# ВАЖНО: на второй половине истории преимущество слабое (+0.122 R/сделку при
# сопоставимом разбросе). Это «не хуже прочего из перебора», а не доказанный эдж.
# Перепроверять — `python backtest.py --all`, см. «Бэктест» в CLAUDE.md.
STOP_MODE = "pct"
STOP_SPREAD = 0.001     # запас в процентах от цены (0.1%) — режим "pct"
STOP_ATR_MULT = 0.5     # множитель ATR — режим "atr"
STOP_ATR_PERIOD = 14

# Фильтр цены входа: сигнал отбрасывается, если риск (закрытие свечи пробоя → её
# экстремум + запас стопа) больше MAX_RISK_ATR × ATR. Большой риск здесь означает
# аномально большую свечу пробоя, то есть вход далеко от уровня, в конце размашистого
# бара — а пружина торгуется ОТ уровня, а не вдогонку. По бэктесту такие входы
# суммарно убыточны, и их отсечение поднимает итог, ОДНОВРЕМЕННО убирая сделки:
# 274 сделки / +77.3R  →  211 сделок / +92.7R (R на сделку +0.282 → +0.440),
# плюс на обеих половинах истории по отдельности (+0.630 и +0.284).
# None или 0 отключает фильтр. Подробности — «Бэктест» в CLAUDE.md.
MAX_RISK_ATR = 1.0

# Работают ли зоны ликвидности как уровни для пробоя (analyzer.liquidity_levels):
#   "off"  — не работают (как было: детектор брал только пики/впадины);
#   "mid"  — цена зоны = середина объёмной свечи;
#   "edge" — цена зоны = её край (low для поддержки, high для сопротивления).
# Зачем вообще: /analyze регулярно советует «сильных часовых уровней нет,
# ориентируйся на зоны ликвидности» и называет по ним точки входа, а детектор их
# игнорировал — бот советовал одно, а сигналил по другому.
LIQ_LEVELS = "off"
# Сколько последних свечей НЕ берём в источник зон. Свеча пробоя сама объёмная по
# построению, и без этого её же середина стала бы «уровнем», который она «пробивает» —
# сигнал из ничего. Исключаем формирующуюся свечу и последнюю закрытую (её как раз
# и проверяет детектор), поэтому 2.
LIQ_SKIP_LAST = 2
# Участвуют ли зоны ликвидности в выборе ЦЕЛИ (а не только в пробое). По замеру —
# нет: зон много, ближайшая цель оказывается слишком близко, R:R не дотягивает до
# порога, и сигнал отбрасывается. В прогоне это срезало число сделок вдвое.
LIQ_AS_TARGET = False
# Фильтр «поглощение» (VSA): у свечи пробоя тело должно быть маленьким относительно
