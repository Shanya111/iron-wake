#   ATR×0.5        112     +15.3     +0.136       +0.279         −0.006
#
# Расширение буфера (до 1.2% и до ATR×3.0) только срезает число сигналов и уводит
# итог в минус: «выбило-и-поехало» падает с 39% до нуля, но вместе с потерями
# уходит и вся прибыль. Риск на сделку задаёт размах свечи пробоя (~1% цены), а не
