VOL_PCTL = 70           # процентиль объёма (режим "pctl"): выше него → аномальный
VOL_WINDOW = 50         # по скольким последним свечам считаем процентиль
VOL_MULT = 1.5          # множитель среднего (режим "mult") — запасной путь и бэктест
# Запас стопа за экстремум свечи пробоя. Два способа задать:
#   STOP_MODE = "pct" — запас = STOP_SPREAD × цена (по умолчанию);
#   STOP_MODE = "atr" — запас = STOP_ATR_MULT × ATR(STOP_ATR_PERIOD) на H1 в момент
#     сигнала: стоп сам подстраивается под волатильность инструмента и момента.
#
# Почему по умолчанию процент, а не ATR. Идея «одним процентом биткоину и золоту не
# угодить» звучит убедительно, но прогон 12 вариантов стопа по 6 инструментам
# (~1200 сигналов, крипта год, золото/нефть 1.5 года) её не подтвердил — процент
