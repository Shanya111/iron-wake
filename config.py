#
# Прогон 9 порогов (--sweep body), 6 инструментов, один срез данных:
#
#   тело ≤   сделок  в мес.  R/сделку  нетто R  калиб.нетто  проверка нетто  просадка
#   выкл        306    17.1    +0.453    +60.8      +49.9         +10.9         22%
#   0.15         66     3.8    +1.164    +58.9      +35.0         +24.0          5%
