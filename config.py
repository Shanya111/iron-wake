#   0.25 ATR        1.72%      61%   -0.050      0.086      -0.136   <- принято
#   0.50 ATR        1.98%      65%   -0.042      0.065      -0.106
#
# Почему не 0.50, хотя по деньгам она лучше: риск сделки уходит к 2% цены при близкой
# цели, и сигнал начинает выглядеть как «рискни двумя процентами, чтобы взять один».
# Решение владельца — середина.
#
# ЧЕСТНО ПРО МЕХАНИЗМ. Улучшение здесь чисто издержечное: комиссия берётся в процентах
# ЦЕНЫ и делится на риск сделки, поэтому широкий стоп дешевле в R. Брутто от ширины
# почти не зависит и отрицателен на всех вариантах. Эджа это не добавляет.
STOP_ATR = 0.25

# За КАКОЙ экстремум ставится стоп: сколько часовых свечей ПЕРЕД свечой свипа берём
# в расчёт вместе с ней. Стоп уходит за ДАЛЬНИЙ из них плюс запас STOP_ATR.
#   0 — только свеча свипа (как было до 2 сентября 2026);
#   1 — свеча свипа и одна перед ней  <- принято.
#
# ЗАЧЕМ. Формулировка владельца: стоп должен стоять за часовым поглощением или за
# часовым фитилём, которым перед ним вынесло по стопам. У нынешнего движка свеча свипа
# и есть тот самый фитиль, а «поглощение» — соседний бар; значит структура сделки это
# ПАРА свечей, и стоп принадлежит паре, а не одной из них.
#
# ИЗМЕРЕНО 2 сентября (stop_struct.py). Правило лучше того стопа, которое заменило:
# нетто -0.190 -> -0.167, винрейт 55% -> 58%, цена сделки 0.123 -> 0.108 R.
#
# НО выигрыш даёт ШИРИНА, а не структура. В том же прогоне рядом считался контроль —
# просто широкий стоп от свечи свипа. При сопоставимой средней ширине (около 1.7% цены)
# контроль идёт чуть ЛУЧШЕ: брутто -0.042 против -0.050, нетто -0.113 против -0.136.
# То есть структура сетапа не несёт информации о будущем; правило полезно тем, что
# подстраивает ширину стопа под размах конкретного сетапа, и только этим.
#
# ВАЖНО ПРО МЕХАНИЗМ, а не про надежду. Широкий стоп удешевляет сделку в R по чистой
# арифметике: издержки берутся в процентах ЦЕНЫ и делятся на риск сделки. Эджа он не
# добавляет — брутто от ширины стопа почти не зависит. То есть это лечение ИЗДЕРЖЕК,
# и выдавать его за прибыльность нельзя.
STOP_STRUCT_BARS = 1

# СИЛА ОТБОЯ: где свеча свипа закрылась внутри собственного размаха. Для лонга 0.6
# значит «закрытие не ниже верхних 40% размаха», для шорта зеркально. Смысл словами:
# прокол должны были ВЫКУПИТЬ решительно, а не еле-еле. Свеча, кое-как переползшая
# уровень обратно, и свеча, вынесшая его импульсом, до 2 сентября 2026 были для
# движка одинаковы — этот порог их различает.
#
# ЭТО ЕДИНСТВЕННЫЙ РЫЧАГ ПРОЕКТА, УЛУЧШИВШИЙ И БРУТТО, И НЕТТО СРАЗУ. Все прежние
# улучшали одно за счёт другого: фильтры строгости поднимали качество отбора и тем же
# движением дорожали в R, широкий стоп удешевлял сделку и не трогал брутто.
#
# ЗАМЕР (edge.py / edge_dose.py / edge_net.py, 2 сентября, 14 инструментов, 20000
# часовых свечей на каждый). Тонкая сетка по семи порогам:
#
#   порог      сигналов/мес   брутто   цена сделки   нетто
#   выкл           466        -0.050      0.086      -0.136
#   >= 0.45        367        -0.037        —          —
#   >= 0.50        348        -0.036      0.060      -0.095
#   >= 0.55        326        -0.033        —          —
#   >= 0.60        302        -0.030      0.055      -0.084   <- принято
#   >= 0.70        248        -0.037        —          —
#
# Улучшение МОНОТОННОЕ до 0.60, обе половины истории идут вместе, дальше разворот.
# Оптимум ВНУТРЕННИЙ, а не на краю сетки, — это собственная проверка проекта на
# «механизм, а не подгонка под диапазон перебора». Первая грубая сетка (0.5/0.66/0.8)
# дала «пик и провал» и едва не привела к неверному выводу; шаг 0.05 показал дугу.
#
# ЗНАЧИМОСТЬ ПРОВЕРЕНА ПРАВИЛЬНЫМ ТЕСТОМ (disp_bos.py, 2 сентября): оставленные
# сделки против ОТБРОШЕННЫХ, а не против нуля. Группы не пересекаются, сравнение
# честное: +3.3 своих ошибки. Прежний t против нуля отвечал на вопрос «надёжно ли мы
# в минусе» и для отбора рычага не годился.
#
# ЦЕНА РЕШЕНИЯ — ЧАСТОТА: 466 -> 302 сигнала в месяц, то есть треть уходит.
#
# ЧЕГО ЭТО НЕ ДЕЛАЕТ. Брутто остаётся ОТРИЦАТЕЛЬНЫМ (-0.030 вместо -0.050 — сорок
# процентов пути до нуля). Прибыльной стратегию порог не делает и не обещает.
# Продолжения у рычага нет: displacement (тот же импульс, но в долях ATR) и BOS
# измерены 2 сентября и отклонены — см. CLAUDE.md, «DISPLACEMENT и BOS».
MIN_CLOSE_POS = 0.6

# ── СВИП ОБЯЗАН БЫТЬ СВИПОМ (5 сентября 2026) ───────────────────────────────
# Сколько свечей ПЕРЕД свечой свипа проверяем на то, что цена была по нужную
# сторону уровня: для лонга хотя бы одна из них должна закрыться ВЫШЕ поддержки.
#
# ЗАЧЕМ. До этой правки детектор спрашивал только «ушёл ли минимум под уровень» и
# «закрылись ли обратно над ним» — и не спрашивал, была ли цена над уровнем ДО
# этого. Любая свеча, выкупившая уровень СНИЗУ, читалась как пружина, хотя
# ликвидность там никто не снимал: цена просто вернулась туда, откуда раньше упала.
#
# Два живых примера, на которых это поймано (оба разобраны в CLAUDE.md):
#   GOLD 2 сентября 11:00 UTC — «поддержкой» служил минимум часовой свечи от
#     1 сентября, то есть уровень СВЕРХУ. Цена пять часов подряд закрывалась под
#     ним (4326 → 4314), потом свеча прошла его вверх и закрылась на 4337.30.
#     Движок выдал сигнал. Свипа не было вообще;
#   BTC 6 июля 15:00 UTC — то же самое, уровень 62376.20, свеча открылась под ним
#     на 62019.90. Стоп получился 61575.82, то есть риск 3% цены при обычных 0.5%.
#
# Это дефект ОПРЕДЕЛЕНИЯ СОБЫТИЯ, а не настройка. Ровно такую ошибку проект уже
# ловил 21 августа в лабораторном momentum.py («детектор считал пробоем любой
# уровень ниже закрытия») и чинил там тем же требованием свежего пересечения;
# в боевой Spring исправление тогда не перенесли.
#
# ПОЧЕМУ ИМЕННО ТРИ, А НЕ ОДНА. Одной свечи мало: сетап бывает двухсвечным —
# свеча А уходит под уровень и закрывается ПОД ним, свеча B выкупает обратно
# (см. SWEEP_WINDOW). Если смотреть только на соседа, у такого сетапа соседом
# окажется сама А, и он отбракуется вместе с браком. Три свечи назад — это окно,
# в которое двухсвечный свип помещается целиком, а «цена давно живёт под уровнем»
# уже не помещается: в обоих примерах выше цена была под уровнем 5+ часов.
#
# ЗАМЕРОМ НЕ ПРОВЕРЕНО. Правка сделана по разбору живых сигналов, а не по прогону:
# это починка ошибки, а не подбор порога. Сколько сигналов она отнимет и что
# сделает с брутто — не измерено; мерить это надо тем же rr_off.py / filters_new.py.
FRESH_CROSS_BARS = 3

# СВИП И ВЫКУП МОГУТ БЫТЬ РАЗНЫМИ СВЕЧАМИ (5 сентября 2026). Сколько свечей назад
# от сигнальной разрешено стоять свече свипа. 0 — прежнее поведение: одна свеча
# обязана и проколоть уровень, и закрыться обратно.
#
# ЗАЧЕМ. Рынок снимает ликвидность не по часам. Типичная последовательность:
# свеча А выносит уровень длинной тенью на объёме и закрывается ПОД ним, свеча B
# выкупает её телом обратно. Глазами это один сетап, а прежний движок не видел его
# вовсе: у А закрытие не вернулось за уровень, у B минимум уже не заходит под него.
#
# Пример (GOLD 2 сентября, M15): 03:30 — свип до 4287.20, объём ×1.81, закрытие
# 4294.49 под пулом; 03:45 — поглощение телом втрое крупнее, закрытие 4308.49,
# отбой 0.97, а объём собственный всего ×0.82. Ни одна свеча по отдельности
# условий не проходит; вместе это ровно тот сетап, ради которого движок и писался.
#
# ЧЕМ ЭТО НЕ ЯВЛЯЕТСЯ. Это НЕ ожидание подтверждения: сигнал уходит по закрытию
# свечи B, ровно как раньше уходил по закрытию свечи свипа. Отложенный вход в этом
# проекте измерен трижды и трижды отклонён (disp_bos.py, m15_entry.py, m15_signal.py):
# пока ждёшь, близкая цель уходит без тебя. Здесь ждать нечего — B уже закрылась.
#
# ЦЕНА: если A ≠ B, от B дополнительно требуется ПОГЛОЩЕНИЕ тела свечи А
# (_engulfs). Без этого правила «две свечи» превратились бы в «любой возврат за
