#
# ВАЖНО: на второй половине истории преимущество слабое (+0.122 R/сделку при
# сопоставимом разбросе). Это «не хуже прочего из перебора», а не доказанный эдж.
# Перепроверять — `python backtest.py --all`, см. «Бэктест» в CLAUDE.md.
STOP_MODE = "pct"
STOP_SPREAD = 0.001     # запас в процентах от цены (0.1%) — режим "pct"
STOP_ATR_MULT = 0.5     # множитель ATR — режим "atr"
STOP_ATR_PERIOD = 14

# Фильтр цены входа: сигнал отбрасывается, если риск (закрытие свечи пробоя → её
# экстремум + запас стопа) больше MAX_RISK_ATR × ATR. Большой риск здесь означает
# аномально большую свечу пробоя, то есть вход далеко от уровня, в конце размашистого
# бара — а пружина торгуется ОТ уровня, а не вдогонку. По бэктесту такие входы
# суммарно убыточны, и их отсечение поднимает итог, ОДНОВРЕМЕННО убирая сделки:
# 274 сделки / +77.3R  →  211 сделок / +92.7R (R на сделку +0.282 → +0.440),
# плюс на обеих половинах истории по отдельности (+0.630 и +0.284).
#
# Это значение фильтра, когда он ВКЛЮЧЁН (кнопка «Не входить вдогонку» в /settings
# пишет именно его). None или 0 отключает. По умолчанию ВКЛЮЧЁН — см. _DEFAULTS.
#
# История решения важнее самих чисел. 5 августа 2026 владелец фильтр ВЫКЛЮЧИЛ: тогда
# в движке было 6 инструментов, фильтр резал частоту с 18 до 4 сигналов в месяц, и бот
# молчал неделями. Довод был про частоту, не про качество отбора.
#
# 7 августа фильтр возвращён, потому что тот довод исчез сам: набор расширен до 20
# инструментов, и с фильтром выходит 45.8 сигнала в месяц вместо 57.8 — он стоит
# 12 сигналов из 58, а не молчащего бота. Цена его отсутствия на расширенном наборе:
#
#   набор            фильтр   сигн./мес   проверочная половина   просадка
#   6 инструментов     вкл       18.1           +7.9R              25%
#   16 инструментов    вкл       45.8          +31.1R              62%
#   16 инструментов    выкл      57.8           −5.8R              81%
#
# То есть на широком наборе фильтр частоту почти не ограничивает, а режет конкретно
# убыточные входы вдогонку — чем больше инструментов, тем он важнее (на 6 давал +42R
# разницы, на 16 — почти +74R). Перепроверять: `python backtest.py --all --bars 8760
# --sweep body --money` (как в бою) против того же с `--no-risk-filter` («как было»).
MAX_RISK_ATR = 1.0

# ── Слой H4 (средний таймфрейм между дневкой и часом) ───────────────────────
# Четырёхчасовые свечи получаются ресемплом из H1 (analyzer.resample_h4), отдельного
# запроса к бирже нет — см. пояснение там же.
#
# H4_LEVELS — участвуют ли уровни H4 в отборе сигналов:
#   False — как было: два слоя, D1 (крупные уровни, ⭐) и H1 (вход);
#   True  — уровни H4 добавляются торгуемыми, и совпадение H1 с H4 даёт ⭐
#           наравне с совпадением с дневкой (analyzer.prioritize_levels).
# В отчёте /analyze слой H4 показывается ВСЕГДА, независимо от этого флага: видеть
# структуру полезно, даже если движок по ней не сигналит.
#
# ВЫКЛЮЧЕН по замеру 7 августа 2026 (`--sweep tf`, 20 инструментов, один срез):
#
#   конфигурация            сделок  R/сделку  нетто R  калибр.  проверка  оба+
#   тренд H1 (принято)         823    +0.328    +68.6    +37.5     +31.1    да
#   тренд H4                  1009    +0.263    +22.1    +45.2     −23.1   нет
#   тренд D1                  1297    +0.267    +40.0    +74.3     −34.3   нет
#   уровни H4 в отборе         886    +0.244     +1.2    −35.1     +36.2   нет
#   тренд H4 + уровни H4      1008    +0.269    +26.4     +5.4     +21.0    да
#
# Главное из замера: часовой тренд делает НАСТОЯЩИЙ отбор. Медленный таймфрейм
# пропускает на 20–60% больше сделок, и каждая хуже. Эдж движка — во входе по факту
# состоявшегося разворота внутри дня, а не в контексте старшего ТФ.
# Уровни H4 вредны отдельно: они попадают не только в пробой, но и в выбор ЦЕЛИ,
# ближайшая цель оказывается ближе, R:R не дотягивает — та же механика, что убила
# зоны ликвидности как уровни. Подробности — «Отклонённая гипотеза: слой H4» в CLAUDE.md.
H4_LEVELS = False

# TREND_TF — какой таймфрейм задаёт направление (фильтр тренда для сигналов):
#   "h1" — часовик, как в бою (перемерян 7 августа 2026 на 20 инструментах, выиграл);
#   "h4" — четырёхчасовик: больше сделок, каждая хуже, проверочная половина в минусе;
#   "d1" — дневка: лучший результат на калибровке (+74.3R) и худший на проверке (−34.3R),
#          наглядный пример, зачем нужно правило обеих половин.
# Заменяет прежний частный флаг бэктеста --trend-d1 (он оставлен как синоним "d1").
TREND_TF = "h1"

# ── Дневка как контекст режима рынка (мягкий гейт) ──────────────────────────
# Идея владельца: дневка задаёт глобальное направление, час даёт точку входа, а
# сделки ПРОТИВ дневки берутся только с сильным подтверждением. Прежний замер
# (--trend-d1) сравнивал не это: там D1 и H1 стояли жёсткими вето друг против друга,
# и дневка проиграла (+10.6R против +77.3R). Гибрид не мерян никогда, и разница
# существенна — мы уже обжигались на ней с MIN_RR: «отобрать сделки с R:R > 3» и
# «требовать R:R ≥ 3 заранее» дали противоположные результаты.
#
# D1_GATE:
#   "off"  — дневка на отбор не влияет (как сейчас в бою);
#   "soft" — сигнал против дневного тренда проходит только с подтверждением
#            (см. D1_CONFIRM); по тренду дневки — как обычно;
#   "hard" — дневка запрещает контртренд полностью. Нужен как контроль: без него
#            в таблице замера не с чем сравнивать "soft".
#
# D1_CONFIRM — что считается подтверждением в режиме "soft":
#   "strong" — пробитый уровень должен быть сильным (⭐, подтверждён старшим ТФ);
#   "volume" — объём свечи пробоя выше повышенного процентиля (D1_CONFIRM_PCTL);
#   "rr"     — сделка должна давать повышенный R:R (D1_CONFIRM_RR).
#
# ВЫКЛЮЧЕН по замеру 7 августа 2026 (`--sweep d1`, 20 инструментов, один срез):
#
#   режим дневки              сделок  R/сделку  нетто R  калибр.  проверка  оба+
#   выкл (принято)               823    +0.328    +68.6    +37.5     +31.1    да
#   мягкий: сильный уровень      518    +0.331    +44.3    +30.3     +14.0    да
#   мягкий: объём P85            665    +0.303    +39.6    +42.3      −2.7   нет
#   мягкий: R:R ≥ 3              664    +0.331    +51.0    +25.8     +25.2    да
#   жёсткий запрет контртренда   501    +0.347    +50.5    +37.9     +12.6    да
#
# Ни один вариант не обошёл текущий на ОБЕИХ половинах. Дневной тренд информацию несёт
# (жёсткий запрет даёт лучший R на сделку, +0.347), но разница в 6% внутри разброса, а
# платит за неё 40% сделок. Жёсткий гейт при этом ОБХОДИТ текущий на калибровке
# (+37.9 против +37.5) и проваливается втрое на проверке — учебный пример, зачем нужно
# правило обеих половин. Подробности — «дневка как мягкий контекст» в CLAUDE.md.
D1_GATE = "off"
D1_CONFIRM = "strong"
D1_CONFIRM_PCTL = 85    # процентиль объёма для подтверждения "volume"
D1_CONFIRM_RR = 3.0     # минимальный R:R для подтверждения "rr"

# Фильтр дистанции входа до пробитого уровня: сигнал отбрасывается, если закрытие
# свечи пробоя ушло от уровня дальше, чем MAX_ENTRY_DIST_ATR × ATR(14). None = выключен.
#
# Чем он отличается от MAX_RISK_ATR, хотя оба «про большую свечу». MAX_RISK_ATR меряет
# РАЗМАХ свечи (закрытие → её экстремум + запас стопа) и от уровня не зависит вообще —
# поэтому считается один раз до перебора уровней. Этот фильтр меряет РАССТОЯНИЕ до
# конкретного уровня, значит живёт внутри цикла по уровням: у разных уровней один и тот
# же бар даёт разный вердикт.
#
# Практическая разница в том, какие сделки они пропускают. Свеча может быть большой
# (MAX_RISK_ATR её забракует), но закрыться вплотную к уровню — а это ровно то, как
# пружина и выглядит по VSA: сняли ликвидность глубоким фитилём и вернулись на уровень.
# Этот фильтр такой вход пропускает, а бракует тот, где цена улетела ОТ уровня и вход
# оказывается вдогонку за ушедшим движением.
#
# ПРИНЯТ 7 августа 2026 со значением 0.5 (`--sweep dist`, 20 инструментов, один срез):
#
#   дистанция  сделок  в мес.  R/сделку  нетто R  калибр.  проверка  лимитом  просадка
#   выкл          823    45.8    +0.328    +68.6    +37.5     +31.1    3 960$      62%
#   ≤ 0.1 ATR     377    21.1    +0.501    +77.5    +33.4     +44.0    3 165$      37%
#   ≤ 0.15 ATR    512    28.5    +0.420    +71.4    +14.3     +57.1    3 358$      48%
#   ≤ 0.2 ATR     612    34.1    +0.395    +76.1    +24.5     +51.6    3 797$      49%
#   ≤ 0.25 ATR    664    36.9    +0.400    +89.9    +34.5     +55.4    4 488$      50%
#   ≤ 0.35 ATR    741    41.2    +0.348    +67.9    +29.1     +38.8    3 802$      56%
#   ≤ 0.5 ATR     793    44.1    +0.349    +78.7    +37.5     +41.2    4 338$      57%
#   ≤ 0.75 ATR    821    45.7    +0.331    +70.7    +38.5     +32.2    4 041$      61%
#
# Убедительна не отдельная строка, а колонка R/сделку: она растёт МОНОТОННО по мере
# ужесточения порога (0.328 → 0.331 → 0.349 → 0.400 → 0.420 → 0.501) на восьми порогах
# подряд. Так выглядит зависимость «доза — эффект», а не удачное ведро: чем ближе вход
# к уровню, тем лучше сделка. Это и подтверждает механику VSA — пружина торгуется ОТ
# уровня.
#
# Почему 0.5, а не 0.25 с лучшей суммой. Правило проекта — «лучший ХУДШИЙ результат»,
# а не пик: у 0.5 худшая половина даёт +37.5R (лучшее значение в таблице), и он не
