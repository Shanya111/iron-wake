# и ни один не вывел движок в плюс. Меню теперь про другое — про строгость отбора
# (два ATR-фильтра ниже), где зависимость «доза — эффект» хотя бы измерена.
VOL_MULT = 1.5          # во сколько раз объём свечи > среднего → аномальный.
                        # Процентиль объёма вместо множителя проверен и отвергнут:
                        # брутто растёт, нетто рушится втрое (сделок втрое больше —
                        # и комиссии втрое больше).
BREAK_PCT = 0.0005      # минимальная глубина ложного пробоя (0.05% цены)
LIQUIDITY_MULT = 1.5    # объём зоны ликвидности > среднего × этого.
                        # Влияет ТОЛЬКО на отображение зон в /analyze, не на отбор.
MIN_RR = 2.0            # минимальный R:R (прибыль/риск): сигнал ниже не берём.
                        #
                        # Убирать этот механизм из КОДА нельзя, и ATR-фильтры его не
                        # заменяют. Он делает ДВЕ вещи: (1) проверяет, что до цели
                        # хватает места, и (2) САМ СТАВИТ ЦЕЛЬ, когда впереди уровня
                        # нет вовсе (цель = MIN_RR × риск). Уберёшь — у части сигналов
                        # не останется цели, а часть пойдёт с целью в треть риска.

# Период ATR (среднего истинного диапазона) — мера волатильности инструмента.
# Нужен двум фильтрам строгости отбора (см. _DEFAULTS) и отчёту /analyze: расстояние
# до уровня в процентах цены у биткоина и у золота значит разное, а в долях ATR —
# одно и то же. 14 — период, на котором калибровались оба фильтра.
ATR_PERIOD = 14

# ── Лимитный вход (заявка вместо входа по рынку) ─────────────────────────────
# ENTRY_PULLBACK — какую долю пути от закрытия свечи пробоя обратно к пробитому
# уровню ждём, прежде чем входить:
#   0    — заявка по цене закрытия свечи;
#   0.5  — на полпути от закрытия к уровню;
#   1.0  — ровно на уровне.
# Ближе к уровню — лучше цена входа при том же стопе и цели (больше R:R), но реже
# исполнение.
#
# ЗАМЕР 19 августа 2026: 14 инструментов BingX, 833 дня часовых свечей, 2397 сделок
# боевого отбора. Набор сделок у всех вариантов ОДИН И ТОТ ЖЕ — меняется только цена
# входа, поэтому колонки сравнимы. «Нетто R» — за вычетом комиссии по ролям
# (мейкер 0.02% вход и цель, тейкер 0.05% стоп) плюс фандинг.
#
#   размещение заявки      сделок  не испол.  упущено R   НЕТТО R (осторожно / оптимист.)
#   по рынку (было)          2397        0%         —        -935.8      -935.8
#   лимит по закрытию        2250        6%      +302.6      -855.1      -706.5
#   откат 0.25               2166       10%      +401.7      -845.6      -706.8
#   откат 0.5  ← принято     2075       13%      +433.1      -768.6      -654.3
#   откат 0.75               1974       18%      +537.9      -809.2      -716.0
#   откат 1.0 (на уровне)    1889       21%      +610.1      -877.4      -799.9
#
# Порядок событий внутри часовой свечи неизвестен (успела ли заявка исполниться до
# того, как цена ушла к цели), поэтому считаны ОБЕ границы — осторожная и
# оптимистичная. 0.5 выигрывает в обеих, и это середина сетки, а не её край: значит
# выбор не упирается в границы перебора.
#
# ЧЕСТНО ПРО ЦЕНУ РЕШЕНИЯ. Колонка «упущено R» — это грязный итог сделок, которые не
# состоялись, потому что цена не откатилась к заявке. Он ПОЛОЖИТЕЛЬНЫЙ и большой:
# лимитка отсекает в первую очередь ВЫИГРЫШНЫЕ сделки (что сразу пошло к цели, то и
# не откатывалось). То есть экономия на комиссии куплена потерей части эджа — это
# адверс-селекция, и она реальна. Лимитный вход всё равно лучше по нетто, но не
# потому, что он «бесплатный», а потому, что рыночный обходится ещё дороже.
ENTRY_PULLBACK = 0.5
# Сколько часов заявка стоит в стакане. Не исполнилась за это время — снимаем,
# сделки не было (статус сигнала 'expired_unfilled').
ENTRY_WAIT_BARS = 4

# ── Трекинг исхода сигналов (2-я волна) ──────────────────────────────────────
