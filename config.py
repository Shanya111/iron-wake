# говорит второй довод, не статистический: «верхние 30% свежих свечей» значат одно и
# то же для золота с Yahoo (объём неполный) и для биткоина с Kraken, а «×1.1» — разное,
# потому что зависит от формы распределения объёма. Проверять — `python backtest.py
