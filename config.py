# ── Строгость отбора: два ATR-фильтра, настраиваются через /settings ─────────
#
# Оба отвечают на один вопрос — «не входим ли мы вдогонку за ушедшим движением».
# Пружина по VSA торгуется ОТ уровня: сняли ликвидность фитилём и вернулись. Вход в
# конце размашистой свечи, далеко от уровня, — это уже погоня, и она в замерах теряет.
#
# 0 = фильтр выключен. По умолчанию оба выключены — это ровно то, что крутится в бою
# сейчас, и точка отсчёта всех замеров.
#
# MAX_ENTRY_DIST_ATR — «вход у уровня»: закрытие свечи пробоя не дальше N×ATR от
#   пробитого уровня. Зависит от КОНКРЕТНОГО уровня, поэтому проверяется внутри цикла
#   по уровням: один и тот же бар бывает «у уровня» для ближнего и «вдогонку» для
#   дальнего.
# MAX_RISK_ATR — «не входить вдогонку»: риск сделки (закрытие → экстремум свечи +
#   запас стопа) не больше N×ATR. Меряет РАЗМАХ свечи и от уровня не зависит вовсе,
#   поэтому считается один раз до перебора уровней.
#
# ЗАМЕР 19–20 августа 2026 (14 инструментов BingX, 833 дня часовых свечей, боевая
# конфигурация как точка отсчёта). «Свежая половина» — вторая половина истории,
# которую отбор порогов не видел; это самая честная оценка «чего ждать дальше».
# Все строки посчитаны в ОДНОЙ конвенции издержек — иначе колонки несравнимы.
#
#   настройка                  сигналов/мес   брутто R/сделку   нетто на свежей половине
#   оба выключены                    88            −0.044               −198.6 R
#   вход ≤ 0.05 ATR                  17            +0.121                +23.7 R
#   вход ≤ 0.075 ATR                 25            +0.139                 +9.2 R
#   вход ≤ 0.1 ATR                   31            +0.094                 −4.7 R
#   вход ≤ 0.15 ATR                  41            +0.055                −32.3 R
#   риск ≤ 0.5 ATR                   28            +0.084                +11.5 R
#   риск ≤ 0.75 ATR                  53            +0.051                −60.8 R
#   риск ≤ 1.0 ATR                   69            +0.006               −128.2 R
#   вход 0.05 + риск 0.5              9            +0.145                +28.1 R
#   вход 0.075 + риск 0.5            13            +0.164                +21.5 R
#   вход 0.1 + риск 0.5              16            +0.161                +32.7 R
#   вход 0.075 + риск 0.75           19            +0.179                +24.8 R
#
# Читается так: чем строже порог, тем лучше средняя сделка и во столько же раз меньше
# сигналов. Зависимость МОНОТОННАЯ в обеих колонках — это «доза — эффект», а не
# удачное ведро.
#
# СОЧЕТАНИЯ ИЗМЕРЕНЫ 20 августа (перебор `--sweep both` в лаборатории) и оказались
# ЛУЧШЕ каждого фильтра поодиночке — и по средней сделке, и на свежей половине. Это
# опровергло ожидание «дистанция арифметически меньше риска, значит вместе будет как
# только дистанция»: фильтры не вложены друг в друга. Порознь они оставляют 683 и 765
# сделок, вместе — 366; риск ≤ 0.5 срезает половину того, что пропускает вход ≤ 0.075.
# Прогон воспроизвёл обе одиночные строки до третьего знака — значит колонки сравнимы.
#
# И честная оговорка, без которой таблица врёт. ПРИБЫЛЬНЫМ движок это не делает.
# Плюс на свежей половине есть, но на калибровочной половине все эти пороги в минусе,
# и по всей истории целиком — тоже в минусе. Механизм известен: фильтры отбирают
# сделки у самого уровня, а у таких сделок УЗКИЙ стоп; издержки берутся в процентах
# от цены и делятся на риск, поэтому цена сделки в R растёт ровно тогда же, когда
# растёт качество отбора. Полная арифметика — в CLAUDE.md, «Замер 19 августа 2026».
_DEFAULTS = {
    "MAX_ENTRY_DIST_ATR": 0.0,  # вход у уровня: 0 = выключен
    "MAX_RISK_ATR": 0.0,        # не входить вдогонку: 0 = выключен
}
_SETTINGS_PATH = Path(__file__).parent / "settings.json"


def _load() -> dict:
    """Общие пороги: дефолты + то, что админ сохранил через /settings.

    Чужие ключи из файла ОТБРАСЫВАЕМ. В боевом settings.json лежат пороги, убранные
    из меню (VOL_MULT, MIN_RR и прочие) — без фильтра они вернулись бы в _runtime и
    всплыли в all_settings(), хотя код их оттуда уже не читает.
    """
    if _SETTINGS_PATH.exists():
        try:
            saved = json.loads(_SETTINGS_PATH.read_text(encoding="utf-8"))
            return {**_DEFAULTS, **{k: v for k, v in saved.items() if k in _DEFAULTS}}
        except Exception:
            return dict(_DEFAULTS)
    return dict(_DEFAULTS)


_runtime = _load()


def get(key: str):
    """Текущее значение настраиваемого порога (с учётом правок через /settings)."""
    return _runtime.get(key, _DEFAULTS.get(key))


def set_value(key: str, value) -> None:
    """Изменить порог и сохранить в settings.json. Используется командой /settings."""
    if key not in _DEFAULTS:
        raise KeyError(key)
    _runtime[key] = value
    _SETTINGS_PATH.write_text(
        json.dumps(_runtime, ensure_ascii=False, indent=2), encoding="utf-8"
    )


def all_settings() -> dict:
    """Все текущие настраиваемые пороги (для отображения в /settings)."""
    return dict(_runtime)


# Ключи, которые подписчик может переопределить персонально (через /settings).
# Это пороги, влияющие на отбор его сигналов; остальные константы — только в коде.
TUNABLE = tuple(_DEFAULTS)


def effective(overrides: dict | None = None) -> dict:
    """Действующие пороги с учётом персональных переопределений пользователя.

    База — общие значения (settings.json / дефолты, задаёт админ). Поверх неё
    кладём личные `overrides` пользователя (из БД). Ключи вне TUNABLE игнорируем.
    Если overrides пуст — вернётся ровно общий набор (как у всех «по умолчанию»).
    """
    base = {k: get(k) for k in _DEFAULTS}
    if overrides:
        base.update({k: v for k, v in overrides.items() if k in _DEFAULTS})
    return base
