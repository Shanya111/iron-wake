LIQUIDITY_MULT = 1.5

# ── Паттерны (Spring / Upthrust) ────────────────────────────────────────────
VOL_LOOKBACK = 20       # сколько свечей берём для среднего объёма
# Как решаем, что объём на свече пробоя аномальный. Два способа:
#   VOL_MODE = "pctl" — объём выше VOL_PCTL-го процентиля за последние VOL_WINDOW
#     свечей, то есть «один из самых высоких столбиков среди соседних» (по умолчанию).
#     Ближе к самой методике VSA: там нет фиксированного множителя, объём относителен.
#   VOL_MODE = "mult" — объём ≥ среднего за VOL_LOOKBACK свечей × VOL_MULT. Как было
#     раньше; оставлен рабочим, на нём бэктест гоняет варианты для сравнения.
# Z-Score сознательно не используем: объём распределён с сильным перекосом, редкие
# выбросы сами раздувают стандартное отклонение и портят меру. Процентиль устойчивее.
#
# Почему P70 за 50 свечей. Прогон 23 вариантов порога (множители ×1.0…×1.5 и
# процентили P50…P95 по окнам 20/50/100) на 6 инструментах, один срез данных:
#
