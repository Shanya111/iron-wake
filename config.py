def sensitivity_of(eff: dict) -> str | None:
    """Какому пресету соответствуют действующие пороги. None — ничему.

    None важен: если вернуть 'mid' наугад, меню поставит галочку на положении,
    в котором пользователь на самом деле не находится (так бывает у тех, кто
    настраивал пороги вручную до появления пресетов). Меню врать не должно —
    оно показывает «своё» и не отмечает ни одну кнопку.
    """
    for name, (_, values) in SENSITIVITY.items():
        if all(eff.get(k) == v for k, v in values.items()):
            return name
    return None


def _load() -> dict:
    if _SETTINGS_PATH.exists():
        try:
            saved = json.loads(_SETTINGS_PATH.read_text(encoding="utf-8"))
            # Берём только известные ключи: в старом файле мог остаться порог,
            # который с тех пор убрали из /settings (например LIQUIDITY_MULT).
            return {**_DEFAULTS, **{k: v for k, v in saved.items() if k in _DEFAULTS}}
        except Exception:
            return dict(_DEFAULTS)
    return dict(_DEFAULTS)


_runtime = _load()


def get(key: str):
    """Текущее значение настраиваемого порога (с учётом правок через /settings)."""
    return _runtime.get(key, _DEFAULTS.get(key))


def set_value(key: str, value) -> None:
    """Изменить порог и сохранить в settings.json. Используется командой /settings."""
    if key not in _DEFAULTS:
        raise KeyError(key)
    _runtime[key] = value
    _SETTINGS_PATH.write_text(
        json.dumps(_runtime, ensure_ascii=False, indent=2), encoding="utf-8"
    )


def all_settings() -> dict:
    """Все текущие настраиваемые пороги (для отображения в /settings)."""
    return dict(_runtime)


# Ключи, которые подписчик может переопределить персонально (через /settings).
# Это пороги, влияющие на отбор его сигналов; остальные константы — только в коде.
TUNABLE = tuple(_DEFAULTS)


def effective(overrides: dict | None = None) -> dict:
    """Действующие пороги с учётом персональных переопределений пользователя.

    База — общие значения (settings.json / дефолты, задаёт админ). Поверх неё
    кладём личные `overrides` пользователя (из БД). Ключи вне TUNABLE игнорируем.
    Если overrides пуст — вернётся ровно общий набор (как у всех «по умолчанию»).
    """
    base = {k: get(k) for k in _DEFAULTS}
    if overrides:
        base.update({k: v for k, v in overrides.items() if k in _DEFAULTS})
    return base
